def font(size: int, bold: bool = False):
    return ImageFont.truetype(FONT_BOLD if bold else FONT_REGULAR, size)


def wrapped(draw: ImageDraw.ImageDraw, text: str, fnt, width: int) -> list[str]:
    lines: list[str] = []
    for paragraph in text.split("\n"):
        words = paragraph.split()
        if not words:
            lines.append("")
            continue
        current = words[0]
        for word in words[1:]:
            candidate = f"{current} {word}"
            if draw.textbbox((0, 0), candidate, font=fnt)[2] <= width:
                current = candidate
            else:
                lines.append(current)
                current = word
        lines.append(current)
    return lines


def fit(draw: ImageDraw.ImageDraw, box, text: str, start=24, minimum=11, bold=False, fill=TEXT, align="center"):
    x0, y0, x1, y1 = box
    for size in range(start, minimum - 1, -1):
        fnt = font(size, bold)
        lines = wrapped(draw, text, fnt, x1 - x0)
        line_height = draw.textbbox((0, 0), "Ag", font=fnt)[3] + 5
        height = line_height * len(lines) - 5
        if height <= y1 - y0:
            y = y0 + ((y1 - y0) - height) / 2
            for line in lines:
                line_width = draw.textbbox((0, 0), line, font=fnt)[2]
                x = x0 if align == "left" else x0 + ((x1 - x0) - line_width) / 2
                draw.text((x, y), line, font=fnt, fill=fill)
                y += line_height
            return
    raise ValueError(f"testo fuori contenitore: {text[:120]}")


def arrow(draw: ImageDraw.ImageDraw, start, end, color=MUTED, width=4):
    draw.line((*start, *end), fill=color, width=width)
    draw.polygon(
        [(end[0], end[1]), (end[0] - 15, end[1] - 9), (end[0] - 15, end[1] + 9)],
        fill=color,
    )



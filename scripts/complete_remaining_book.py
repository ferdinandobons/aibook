def validate_image(path: Path):
    with Image.open(path) as image:
        image.verify()
    with Image.open(path) as image:
        assert image.mode == "RGB", path
        assert image.size == (1800, 1000), path
        rgb = image.convert("RGB")
        assert rgb.getpixel((0, 0)) == (255, 255, 255), path
        assert rgb.getpixel((1799, 999)) == (255, 255, 255), path


